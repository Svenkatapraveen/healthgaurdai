String getDepartmentName(String rawInput) {
  final clean = rawInput.trim();
  if (specialtyToDepartmentMap.containsKey(clean)) {
    return specialtyToDepartmentMap[clean]!;
  }
  for (var entry in specialtyToDepartmentMap.entries) {
    if (clean.toLowerCase().contains(entry.key.toLowerCase())) {
      return entry.value;
    }
  }
  return 'General Medicine';
}

